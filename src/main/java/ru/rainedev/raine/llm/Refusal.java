package ru.rainedev.raine.llm;

import java.util.regex.Pattern;

/**
 * Ответ модели, в котором вместо дела стоят извинения.
 * <p>
 * Опасен он тем, что непустой, а значит, идёт дальше как обычный результат:
 * оседает в кэше навсегда (значит, вложение уже никогда не переспросят), уходит
 * в разговор как увиденное или услышанное и попадает в дневник. Из одной такой
 * записи она вывела, что не умеет смотреть видео.
 */
public final class Refusal {

    /**
     * Смотрим только начало ответа: описание начинается с заголовка, а отказ —
     * сразу с извинения. Иначе «I can't» внутри подписи к картинке считалось бы
     * отказом, и настоящее описание пропадало бы.
     */
    private static final Pattern APOLOGY = Pattern.compile(
            "^\\W*(?:i(?:'m| am)?\\s+(?:sorry|unable|afraid)|i\\s+can(?:'t|not)|sorry[,.]|as an ai"
                    + "|извини|прост(?:и|ите)|я не могу|не могу (?:помочь|описать|услышать|прослушать)"
                    + "|я не слышу|не слышно)",
            Pattern.CASE_INSENSITIVE);

    private Refusal() {
    }

    /** @return правда, если модель не посмотрела и не услышала, а извинилась */
    public static boolean detected(String answer) {
        return answer != null && APOLOGY.matcher(answer.strip()).find();
    }
}
